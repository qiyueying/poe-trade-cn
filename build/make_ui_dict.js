/* Build a Simplified-Chinese UI dictionary from the old POE Trade ZH
 * Traditional-Chinese string table, then add mainland PoE terminology.
 */
const fs = require('fs');
const path = require('path');
const vm = require('vm');
const OpenCC = require('../tools/openccjs/t2cn.js');

const root = path.resolve(__dirname, '..');
const src = path.join(root, 'ref', 'poe-trade-zh', 'js', 'translate.zh_TW.js');
let code = fs.readFileSync(src, 'utf8');
code = code.replace('const __ =', 'globalThis.__ =');
const ctx = {};
vm.createContext(ctx);
vm.runInContext(code, ctx);

const convert = OpenCC.Converter({ from: 'tw', to: 'cn' });
const ui = {};
for (const [key, value] of Object.entries(ctx.__ || {})) {
  if (typeof value !== 'string' || !value.trim()) continue;
  ui[key] = convert(value);
}

